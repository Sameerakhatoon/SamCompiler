// B1: `ins reg, [sp, #off]` for an 8-byte ldr or str, through x12
// when off is past the scaled 12-bit offset.
static void codegen_sp_word(const char* ins, const char* reg, int off){
    if(off <= 32760){
        asm_push("%s %s, [sp, #%i]", ins, reg, off);
        return;
    }
    codegen_add_imm("x12", "sp", off);
    asm_push("%s %s, [x12]", ins, reg);
}

// The arguments of a simple call (exp64_call_is_simple): the register
// words are popped into x0-x7; the rest stay where they are as the
// stack arguments, packed from 16-byte slots down to the 8-byte ones
// AAPCS64 wants (sp stays 16-byte aligned: the area keeps its size).
// Returns the bytes left above sp.
static int aarch64_call_simple(const struct exp64_call* call){
    int stack_args = call->slots - call->reg_words;
    for(int i = 0; i < call->reg_words; i++){
        asm_push_ins_pop(codegen_arg_registers[call->first_reg + i], STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    for(int i = 1; i < stack_args; i++){
        asm_push("ldr x11, [sp, #%i]", CODEGEN_SLOT * i);
        asm_push("str x11, [sp, #%i]", 8 * i);
    }
    for(int i = 0; i < stack_args; i++){
        stackframe_pop_expecting(current_function, STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    return CODEGEN_SLOT * stack_args;
}

// B1: the arguments of any other call. An outgoing area goes below
// the expression stack: the stack words are copied to it in order,
// a struct passed by reference gets its copy there too, then the
// register words are loaded from their slots. Returns the bytes above
// sp: the area and the slots.
static int aarch64_call_general(const struct exp64_call* call){
    int area = align_value(call->area, CODEGEN_SLOT);
    codegen_stack_sp_change(-area);
    for(int pass = 0; pass < 2; pass++){
        for(int i = 0; i < call->count; i++){
            const struct exp64_arg* a = &call->args[i];
            int from = area + CODEGEN_SLOT * a->slot;
            if(a->kind == EXP64_ARG_REF){
                if(pass == 0){
                    for(int w = 0; w < a->words; w++){
                        codegen_sp_word("ldr", "x11", from + CODEGEN_SLOT * w);
                        codegen_sp_word("str", "x11", a->copy + 8 * w);
                    }
                    if(a->stack >= 0){
                        codegen_add_imm("x11", "sp", a->copy);
                        codegen_sp_word("str", "x11", 8 * a->stack);
                    }
                } else if(a->reg >= 0){
                    codegen_add_imm(codegen_arg_registers[a->reg], "sp", a->copy);
                }
                continue;
            }
            if(a->fp){
                if(pass == 1 && a->size == 16){
                    // a long double, its words in two slots.
                    aarch64_ld_load_q(a->reg, from, from + CODEGEN_SLOT);
                } else if(pass == 1){
                    char reg[8];
                    snprintf(reg, sizeof(reg), "d%i", a->reg);
                    codegen_sp_word("ldr", reg, from);
                }
                continue;
            }
            if(a->pieces){
                // a homogeneous floating-point aggregate, a
                // member to each s or d register. Its words are in
                // 16-byte slots.
                for(int k = 0; k < a->pieces && pass == 1; k++){
                    const struct exp64_piece* p = &a->piece[k];
                    int at = from + CODEGEN_SLOT * (p->offset / 8) + p->offset % 8;
                    if(p->size == 16){
                        aarch64_ld_load_q(p->reg, at, at + CODEGEN_SLOT);
                        continue;
                    }
                    codegen_sp_word("ldr", aarch64_freg(p->reg, p->size), at);
                }
                continue;
            }
            for(int w = 0; w < a->words; w++){
                if(w >= a->reg_words && pass == 0){
                    codegen_sp_word("ldr", "x11", from + CODEGEN_SLOT * w);
                    codegen_sp_word("str", "x11", 8 * (a->stack + w - a->reg_words));
                } else if(w < a->reg_words && pass == 1){
                    codegen_sp_word("ldr", codegen_arg_registers[a->reg + w], from + CODEGEN_SLOT * w);
                }
            }
        }
    }
    for(int i = 0; i < call->slots; i++){
        stackframe_pop(current_function);
    }
    return area + CODEGEN_SLOT * call->slots;
}

// A call. The arguments are on the expression stack over the callee's
// address (when it is not a named function) and the room for a
// returned struct. A struct of up to 16 bytes comes back in x0:x1 and
// is stored into the room; a bigger one is written there through x8.
static void aarch64_call(const struct exp64_call* call){
    int above = call->simple ? aarch64_call_simple(call) : aarch64_call_general(call);
    if(call->symbol){
        codegen_c_symbol_into("x9", call->symbol);
    } else {
        codegen_sp_word("ldr", "x9", above);
    }
    if(call->struct_size && !call->struct_in_regs){
        codegen_add_imm("x8", "sp", above + (call->symbol ? 0 : CODEGEN_SLOT));
    }
    asm_push("blr x9");
    codegen_stack_sp_change(above);
    if(!call->symbol){
        asm_push_ins_pop("x9", STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    if(call->float_return){
        aarch64_from_freg(0, call->float_return);
    }
    if(call->struct_size){
        if(call->ld_return){
            // a long double comes back in q0.
            asm_push("str q0, [sp]");
        } else if(call->return_pieces){
            // an aggregate from s0-s3 or d0-d3.
            for(int k = 0; k < call->return_pieces; k++){
                const struct exp64_piece* p = &call->return_piece[k];
                asm_push("str %s, [sp, #%i]", aarch64_freg(p->reg, p->size), p->offset);
            }
        } else if(call->struct_in_regs){
            asm_push(call->struct_size > 8 ? "stp x0, x1, [sp]" : "str x0, [sp]");
        }
        asm_push("mov x0, sp");
    }
}

static void aarch64_asm_text(const char* text){
    asm_push("%s", text);
}

// ---------------------------------------------------------------
// Floating point. A value travels in x0 as its bits and is moved to d0
// or s0 (the right operand from x1 to d1 or s1) for each operation; x1
// is kept.
// ---------------------------------------------------------------

// The d or s register n, for a double or a float.
static const char* aarch64_freg(int n, int size){
    static char buffers[4][8];
    static int next;
    char* out = buffers[next++ % 4];
    snprintf(out, sizeof(buffers[0]), "%c%i", size == DATA_SIZE_DWORD ? 's' : size == 16 ? 'q' : 'd', n);
    return out;
}

static void aarch64_to_freg(int n, int reg, int size){
    asm_push("fmov %s, %s", aarch64_freg(n, size), size == DATA_SIZE_DWORD ? aarch64_wreg(reg) : aarch64_reg(reg));
}

static void aarch64_from_freg(int n, int size){
    asm_push("fmov %s, %s", size == DATA_SIZE_DWORD ? "w0" : "x0", aarch64_freg(n, size));
}

static void aarch64_fbinop(const char* op, int size){
    const char* ins = S_EQ(op, "+") ? "fadd" : S_EQ(op, "-") ? "fsub" : S_EQ(op, "*") ? "fmul" : "fdiv";
    aarch64_to_freg(0, 0, size);
    aarch64_to_freg(1, 1, size);
    asm_push("%s %s, %s, %s", ins, aarch64_freg(0, size), aarch64_freg(0, size), aarch64_freg(1, size));
    aarch64_from_freg(0, size);
}

// fcmp of an unordered pair (a NaN) sets C and V: mi, ls, gt and ge are
// then false, ne true.
static void aarch64_fcompare(const char* op, int size){
    const char* cond = 0;
    if(S_EQ(op, "=="))      cond = "eq";
    else if(S_EQ(op, "!=")) cond = "ne";
    else if(S_EQ(op, "<"))  cond = "mi";
    else if(S_EQ(op, ">"))  cond = "gt";
    else if(S_EQ(op, "<=")) cond = "ls";
    else                    cond = "ge";
    aarch64_to_freg(0, 0, size);
    aarch64_to_freg(1, 1, size);
    asm_push("fcmp %s, %s", aarch64_freg(0, size), aarch64_freg(1, size));
    asm_push("cset w0, %s", cond);
}

static void aarch64_int_to_float(int size, bool from_u64){
    asm_push("%s %s, x0", from_u64 ? "ucvtf" : "scvtf", aarch64_freg(0, size));
    aarch64_from_freg(0, size);
}

static void aarch64_float_to_int(int size, bool to_u64){
    aarch64_to_freg(0, 0, size);
    asm_push("%s x0, %s", to_u64 ? "fcvtzu" : "fcvtzs", aarch64_freg(0, size));
}

static void aarch64_float_resize(int from, int to){
    aarch64_to_freg(0, 0, from);
    asm_push("fcvt %s, %s", aarch64_freg(0, to), aarch64_freg(0, from));
    aarch64_from_freg(0, to);
}

// the stack pointer, for variable-length arrays.
static void aarch64_sp_get(void){
    asm_push("mov x0, sp");
}

static void aarch64_sp_set(void){
    asm_push("mov sp, x0");
}

// ---------------------------------------------------------------
// long double, IEEE binary128, through the libgcc soft-float
// routines, which take and give it in q registers. A value is its
// address in x0 (x1 for the right operand).
// ---------------------------------------------------------------

static void aarch64_slot_address(int slots){
    codegen_add_imm("x0", "sp", CODEGEN_SLOT * slots);
}

static void aarch64_ld_arith(const char* op){
    const char* routine = S_EQ(op, "+") ? "__addtf3" : S_EQ(op, "-") ? "__subtf3" : S_EQ(op, "*") ? "__multf3" : "__divtf3";
    asm_push("ldr q0, [x0]");
    asm_push("ldr q1, [x1]");
    asm_push("bl %s", routine);
    asm_push("str q0, [sp]");
    asm_push("mov x0, sp");
}

// The comparison routines give an int whose sign says the answer, and
// the one that makes the comparison false for an unordered pair.
static void aarch64_ld_compare(const char* op){
    const char* routine = S_EQ(op, "==") ? "__eqtf2" : S_EQ(op, "!=") ? "__netf2" : S_EQ(op, "<") ? "__lttf2"
                        : S_EQ(op, "<=") ? "__letf2" : S_EQ(op, ">") ? "__gttf2" : "__getf2";
    const char* cond = S_EQ(op, "==") ? "eq" : S_EQ(op, "!=") ? "ne" : S_EQ(op, "<") ? "lt"
                     : S_EQ(op, "<=") ? "le" : S_EQ(op, ">") ? "gt" : "ge";
    asm_push("ldr q0, [x0]");
    asm_push("ldr q1, [x1]");
    asm_push("bl %s", routine);
    asm_push("cmp w0, #0");
    asm_push("cset w0, %s", cond);
}

static void aarch64_ld_truth(void){
    asm_push("ldr q0, [x0]");
    asm_push("movi v1.2d, #0");
    asm_push("bl __netf2");
    asm_push("cmp w0, #0");
    asm_push("cset w0, ne");
}

static void aarch64_ld_from(int kind){
    if(kind == EXP64_LD_FLOAT){
        asm_push("fmov s0, w0");
        asm_push("bl __extendsftf2");
    } else if(kind == EXP64_LD_DOUBLE){
        asm_push("fmov d0, x0");
        asm_push("bl __extenddftf2");
    } else {
        asm_push("bl %s", kind == EXP64_LD_S64 ? "__floatditf" : "__floatunditf");
    }
    asm_push("str q0, [sp]");
    asm_push("mov x0, sp");
}

static void aarch64_ld_to(int kind){
    asm_push("ldr q0, [x0]");
    if(kind == EXP64_LD_FLOAT){
        asm_push("bl __trunctfsf2");
        asm_push("fmov w0, s0");
    } else if(kind == EXP64_LD_DOUBLE){
        asm_push("bl __trunctfdf2");
        asm_push("fmov x0, d0");
    } else {
        asm_push("bl %s", kind == EXP64_LD_S64 ? "__fixtfdi" : "__fixunstfdi");
    }
}

static void aarch64_ld_spill_q(int reg, int offset){
    codegen_add_imm("x11", "x29", offset);
    asm_push("str q%i, [x11]", reg);
}

// q<reg> = the long double in two 8-byte words at sp + off and sp + off2.
static void aarch64_ld_load_q(int reg, int off, int off2){
    char d[8];
    snprintf(d, sizeof(d), "d%i", reg);
    codegen_sp_word("ldr", d, off);
    codegen_sp_word("ldr", "x11", off2);
    asm_push("mov v%i.d[1], x11", reg);
}

