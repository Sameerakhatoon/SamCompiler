// mul has no immediate form.
static void aarch64_mul_imm(int reg, long long value){
    if(value != 1){
        codegen_mov_imm("x12", value);
        asm_push("mul %s, %s, x12", aarch64_reg(reg), aarch64_reg(reg));
    }
}

static void aarch64_load(int size, bool is_signed){
    switch(size){
        case DATA_SIZE_BYTE:
            asm_push(is_signed ? "ldrsb x0, [x0]" : "ldrb w0, [x0]");
            break;
        case DATA_SIZE_WORD:
            asm_push(is_signed ? "ldrsh x0, [x0]" : "ldrh w0, [x0]");
            break;
        case DATA_SIZE_DWORD:
            // A w-register load clears the top half by itself.
            asm_push(is_signed ? "ldrsw x0, [x0]" : "ldr w0, [x0]");
            break;
        default:
            asm_push("ldr x0, [x0]");
            break;
    }
}

static void aarch64_store(int size){
    switch(size){
        case DATA_SIZE_BYTE:  asm_push("strb w0, [x1]"); break;
        case DATA_SIZE_WORD:  asm_push("strh w0, [x1]"); break;
        case DATA_SIZE_DWORD: asm_push("str w0, [x1]"); break;
        default:              asm_push("str x0, [x1]"); break;
    }
}

// One piece of a copy or a clear: the size of the next access at
// offset `off` of `size` bytes. Offsets stay multiples of the piece,
// as the scaled ldr/str offsets want.
static int aarch64_piece(int off, int size){
    int left = size - off;
    return left >= 8 ? 8 : left >= 4 ? 4 : left >= 2 ? 2 : 1;
}

static const char* aarch64_piece_suffix(int piece){
    return piece == 1 ? "b" : piece == 2 ? "h" : "";
}

// Copy `size` bytes from [x1] to [x0] through x11.
static void aarch64_copy(int size){
    for(int off = 0; off < size; ){
        int piece = aarch64_piece(off, size);
        const char* r = piece == 8 ? "x11" : "w11";
        asm_push("ldr%s %s, [x1, #%i]", aarch64_piece_suffix(piece), r, off);
        asm_push("str%s %s, [x0, #%i]", aarch64_piece_suffix(piece), r, off);
        off += piece;
    }
}

// B1: the `size` (1 to 8) bytes at [base, #off] into x<dst>, zero
// extended, reading no byte past them: 3, 5, 6 and 7 bytes are put
// together from 4, 2 and 1 byte pieces through x13.
static void aarch64_load_bytes(int dst, const char* base, int off, int size){
    for(int done = 0; done < size; ){
        int piece = aarch64_piece(done, size);
        int r = done ? 13 : dst;
        asm_push("ldr%s %s%i, [%s, #%i]", aarch64_piece_suffix(piece), piece == 8 ? "x" : "w", r, base, off + done);
        if(done){
            asm_push("orr x%i, x%i, x13, lsl #%i", dst, dst, 8 * done);
        }
        done += piece;
    }
}

static void aarch64_push_struct(int size){
    struct datatype word = { .type = DATA_TYPE_LONG, .type_str = "long", .size = DATA_SIZE_DDWORD };
    asm_push("mov x11, x0");
    for(int w = align_value(size, DATA_SIZE_DDWORD) / DATA_SIZE_DDWORD - 1; w >= 0; w--){
        int bytes = size - DATA_SIZE_DDWORD * w;
        const char* base = "x11";
        int off = DATA_SIZE_DDWORD * w;
        if(off + DATA_SIZE_DDWORD > 4096){
            codegen_add_imm("x12", "x11", off);
            base = "x12";
            off = 0;
        }
        aarch64_load_bytes(0, base, off, bytes > DATA_SIZE_DDWORD ? DATA_SIZE_DDWORD : bytes);
        aarch64_push(&word);
    }
}

static void aarch64_zero_frame(int offset, int size){
    codegen_add_imm("x11", "x29", offset);
    for(int off = 0; off < size; ){
        int piece = aarch64_piece(off, size);
        asm_push("str%s %s, [x11, #%i]", aarch64_piece_suffix(piece), piece == 8 ? "xzr" : "wzr", off);
        off += piece;
    }
}

// Widen the low `size` bytes of a register back to a canonical 64-bit
// value.
static void aarch64_extend(int reg, int size, bool is_signed){
    const char* x = aarch64_reg(reg);
    const char* w = aarch64_wreg(reg);
    switch(size){
        case DATA_SIZE_BYTE:
            if(is_signed) asm_push("sxtb %s, %s", x, w);
            else          asm_push("and %s, %s, #0xff", w, w);
            break;
        case DATA_SIZE_WORD:
            if(is_signed) asm_push("sxth %s, %s", x, w);
            else          asm_push("and %s, %s, #0xffff", w, w);
            break;
        case DATA_SIZE_DWORD:
            if(is_signed) asm_push("sxtw %s, %s", x, w);
            else          asm_push("mov %s, %s", w, w);
            break;
    }
}

// x0 = x0 <op> x1 on 32 or 64 bits. exp64 re-extends a 32-bit result.
static void aarch64_binop(const char* op, int size, bool is_signed){
    bool wide = size == DATA_SIZE_DDWORD;
    const char* a = wide ? "x0" : "w0";
    const char* c = wide ? "x1" : "w1";
    const char* t = wide ? "x2" : "w2";
    if(S_EQ(op, "+"))       asm_push("add %s, %s, %s", a, a, c);
    else if(S_EQ(op, "-"))  asm_push("sub %s, %s, %s", a, a, c);
    else if(S_EQ(op, "*"))  asm_push("mul %s, %s, %s", a, a, c);
    else if(S_EQ(op, "&"))  asm_push("and %s, %s, %s", a, a, c);
    else if(S_EQ(op, "|"))  asm_push("orr %s, %s, %s", a, a, c);
    else if(S_EQ(op, "^"))  asm_push("eor %s, %s, %s", a, a, c);
    else if(S_EQ(op, "<<")) asm_push("lsl %s, %s, %s", a, a, c);
    else if(S_EQ(op, ">>")) asm_push("%s %s, %s, %s", is_signed ? "asr" : "lsr", a, a, c);
    else if(S_EQ(op, "/"))  asm_push("%s %s, %s, %s", is_signed ? "sdiv" : "udiv", a, a, c);
    else if(S_EQ(op, "%")){
        // There is no remainder instruction: a - (a / c) * c.
        asm_push("%s %s, %s, %s", is_signed ? "sdiv" : "udiv", t, a, c);
        asm_push("msub %s, %s, %s, %s", a, t, c, a);
    } else {
        compiler_error(current_process, "aarch64: no instruction for %s\n", op);
    }
}

// Both values are canonical, so one 64-bit compare serves every type;
// the condition picks signed or unsigned.
static void aarch64_compare(const char* op, bool is_signed){
    const char* cond = 0;
    if(S_EQ(op, "=="))      cond = "eq";
    else if(S_EQ(op, "!=")) cond = "ne";
    else if(S_EQ(op, "<"))  cond = is_signed ? "lt" : "lo";
    else if(S_EQ(op, ">"))  cond = is_signed ? "gt" : "hi";
    else if(S_EQ(op, "<=")) cond = is_signed ? "le" : "ls";
    else                    cond = is_signed ? "ge" : "hs";
    asm_push("cmp x0, x1");
    asm_push("cset w0, %s", cond);
}

static void aarch64_unop(const char* op, int size){
    const char* a = size == DATA_SIZE_DDWORD ? "x0" : "w0";
    if(S_EQ(op, "-")){
        asm_push("neg %s, %s", a, a);
    } else if(S_EQ(op, "~")){
        asm_push("mvn %s, %s", a, a);
    } else {
        asm_push("cmp x0, #0");
        asm_push("cset w0, eq");
    }
}

static void aarch64_branch(int label, int when){
    if(when == EXP64_BRANCH_ALWAYS){
        asm_push("b .Lexp_%i", label);
        return;
    }
    asm_push("%s x0, .Lexp_%i", when == EXP64_BRANCH_IF_ZERO ? "cbz" : "cbnz", label);
}

static void aarch64_branch_false(const char* op, bool is_signed, const char* label){
    if(!op){
        asm_push("cbz x0, %s", label);
        return;
    }
    const char* cond = 0;
    if(S_EQ(op, "=="))      cond = "ne";
    else if(S_EQ(op, "!=")) cond = "eq";
    else if(S_EQ(op, "<"))  cond = is_signed ? "ge" : "hs";
    else if(S_EQ(op, ">"))  cond = is_signed ? "le" : "ls";
    else if(S_EQ(op, "<=")) cond = is_signed ? "gt" : "hi";
    else                    cond = is_signed ? "lt" : "lo";
    asm_push("cmp x0, x1");
    asm_push("b.%s %s", cond, label);
}

static void aarch64_label(int label){
    asm_push(".Lexp_%i:", label);
}

