static void x86_64_from_xmm(const char* reg, int n, int size);
static void x86_64_to_xmm(int n, const char* reg, int size);

static const char* x86_64_reg(int reg){
    return reg ? "rcx" : "rax";
}

static void x86_64_push(struct datatype* dtype){
    asm_push_ins_push_with_data("rax", STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value", 0,
        &(struct stack_frame_data){.dtype = *dtype});
}

// B1: the `size` (1 to 8) bytes at [base+off] into the 64-bit register
// dst, zero extended, reading no byte past them: 3, 5, 6 and 7 bytes
// are put together from 4, 2 and 1 byte pieces through rcx.
static void x86_64_load_bytes(const char* dst, const char* base, int off, int size){
    char address[64];
    for(int done = 0; done < size; ){
        int piece = size - done >= 8 ? 8 : size - done >= 4 ? 4 : size - done >= 2 ? 2 : 1;
        snprintf(address, sizeof(address), "%s+%i", base, off + done);
        codegen_load_register(done ? "rcx" : dst, address, piece, false);
        if(done){
            asm_push("shl rcx, %i", 8 * done);
            asm_push("or %s, rcx", dst);
        }
        done += piece;
    }
}

static void x86_64_push_struct(int size){
    struct datatype word = { .type = DATA_TYPE_LONG, .type_str = "long", .size = DATA_SIZE_DDWORD };
    asm_push("mov r11, rax");
    for(int w = align_value(size, DATA_SIZE_DDWORD) / DATA_SIZE_DDWORD - 1; w >= 0; w--){
        int bytes = size - DATA_SIZE_DDWORD * w;
        x86_64_load_bytes("rax", "r11", DATA_SIZE_DDWORD * w, bytes > DATA_SIZE_DDWORD ? DATA_SIZE_DDWORD : bytes);
        x86_64_push(&word);
    }
}

static void x86_64_pop(int reg){
    asm_push_ins_pop(x86_64_reg(reg), STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
}

static void x86_64_mov_r1(void){
    asm_push("mov rcx, rax");
}

static void x86_64_swap(void){
    asm_push("xchg rax, rcx");
}

static void x86_64_imm(int reg, long long value){
    if(value == 0){
        asm_push("xor %s, %s", codegen_sub_register(x86_64_reg(reg), DATA_SIZE_DWORD), codegen_sub_register(x86_64_reg(reg), DATA_SIZE_DWORD));
        return;
    }
    asm_push("mov %s, %lld", x86_64_reg(reg), value);
}

static void x86_64_frame_address(int offset){
    asm_push("lea rax, [rbp%+i]", offset);
}

// reg = the address of a symbol. One this file defines is rip-relative
// (`default rel`); any other may be in a shared library, so a PIE
// reads its address from the GOT.
static void codegen_symbol_into(const char* reg, const char* name){
    if(symbol_defined_in_tree(current_process, name)){
        asm_push("lea %s, [%s]", reg, codegen_symbol(name));
        return;
    }
    asm_push("mov %s, [rel %s wrt ..gotpc]", reg, codegen_symbol(name));
}

static void x86_64_symbol_address(const char* name){
    codegen_symbol_into("rax", name);
}

// String literals live in .rodata; `lea` with `default rel` gives a
// rip-relative address.
static void x86_64_string_address(const char* str){
    asm_push("lea rax, [%s]", codegen_register_string(str));
}

static bool x86_64_fits_imm32(long long value){
    return value >= -2147483648LL && value <= 2147483647LL;
}

static void x86_64_add_imm(long long value){
    if(value == 0){
        return;
    }
    if(x86_64_fits_imm32(value)){
        asm_push("add rax, %lld", value);
        return;
    }
    asm_push("mov r11, %lld", value);
    asm_push("add rax, r11");
}

static void x86_64_mul_imm(int reg, long long value){
    if(value != 1){
        asm_push("imul %s, %s, %lld", x86_64_reg(reg), x86_64_reg(reg), value);
    }
}

static void x86_64_load(int size, bool is_signed){
    codegen_load_register("rax", "rax", size, is_signed);
}

static void x86_64_store(int size){
    asm_push("mov %s [rcx], %s", codegen_size_keyword(size), codegen_sub_register("rax", size));
}

// Copy `size` bytes from [rcx] to [rax] in 8, 4, 2 and 1 byte pieces.
static void x86_64_copy(int size){
    for(int off = 0; off < size; ){
        int piece = size - off >= 8 ? 8 : size - off >= 4 ? 4 : size - off >= 2 ? 2 : 1;
        const char* r = codegen_sub_register("r11", piece);
        asm_push("mov %s, %s [rcx+%i]", r, codegen_size_keyword(piece), off);
        asm_push("mov %s [rax+%i], %s", codegen_size_keyword(piece), off, r);
        off += piece;
    }
}

static void x86_64_zero_frame(int offset, int size){
    for(int off = 0; off < size; ){
        int piece = size - off >= 8 ? 8 : size - off >= 4 ? 4 : size - off >= 2 ? 2 : 1;
        asm_push("mov %s [rbp%+i], 0", codegen_size_keyword(piece), offset + off);
        off += piece;
    }
}

// Widen the low `size` bytes of a register back to a canonical 64-bit
// value.
static void x86_64_extend(int reg, int size, bool is_signed){
    const char* r = x86_64_reg(reg);
    const char* r32 = codegen_sub_register(r, DATA_SIZE_DWORD);
    switch(size){
        case DATA_SIZE_BYTE:
            if(is_signed) asm_push("movsx %s, %s", r, codegen_sub_register(r, DATA_SIZE_BYTE));
            else          asm_push("movzx %s, %s", r32, codegen_sub_register(r, DATA_SIZE_BYTE));
            break;
        case DATA_SIZE_WORD:
            if(is_signed) asm_push("movsx %s, %s", r, codegen_sub_register(r, DATA_SIZE_WORD));
            else          asm_push("movzx %s, %s", r32, codegen_sub_register(r, DATA_SIZE_WORD));
            break;
        case DATA_SIZE_DWORD:
            if(is_signed) asm_push("movsxd %s, %s", r, r32);
            else          asm_push("mov %s, %s", r32, r32);
            break;
    }
}

// rax = rax <op> rcx on 32 or 64 bits. exp64 re-extends a 32-bit
// result.
static void x86_64_binop(const char* op, int size, bool is_signed){
    bool wide = size == DATA_SIZE_DDWORD;
    const char* a = wide ? "rax" : "eax";
    const char* c = wide ? "rcx" : "ecx";
    if(S_EQ(op, "+"))       asm_push("add %s, %s", a, c);
    else if(S_EQ(op, "-"))  asm_push("sub %s, %s", a, c);
    else if(S_EQ(op, "*"))  asm_push("imul %s, %s", a, c);
    else if(S_EQ(op, "&"))  asm_push("and %s, %s", a, c);
    else if(S_EQ(op, "|"))  asm_push("or %s, %s", a, c);
    else if(S_EQ(op, "^"))  asm_push("xor %s, %s", a, c);
    else if(S_EQ(op, "<<")) asm_push("shl %s, cl", a);
    else if(S_EQ(op, ">>")) asm_push("%s %s, cl", is_signed ? "sar" : "shr", a);
    else if(S_EQ(op, "/") || S_EQ(op, "%")){
        if(is_signed){
            asm_push(wide ? "cqo" : "cdq");
            asm_push("idiv %s", c);
        } else {
            asm_push("xor edx, edx");
            asm_push("div %s", c);
        }
        if(S_EQ(op, "%")){
            asm_push(wide ? "mov rax, rdx" : "mov eax, edx");
        }
    } else {
        compiler_error(current_process, "x86_64: no instruction for %s\n", op);
    }
}

// Both values are canonical, so one 64-bit compare serves every type;
// the condition picks signed or unsigned.
static void x86_64_compare(const char* op, bool is_signed){
    const char* set = 0;
    if(S_EQ(op, "=="))      set = "sete";
    else if(S_EQ(op, "!=")) set = "setne";
    else if(S_EQ(op, "<"))  set = is_signed ? "setl"  : "setb";
    else if(S_EQ(op, ">"))  set = is_signed ? "setg"  : "seta";
    else if(S_EQ(op, "<=")) set = is_signed ? "setle" : "setbe";
    else                    set = is_signed ? "setge" : "setae";
    asm_push("cmp rax, rcx");
    asm_push("%s al", set);
    asm_push("movzx eax, al");
}

static void x86_64_unop(const char* op, int size){
    const char* a = size == DATA_SIZE_DDWORD ? "rax" : "eax";
    if(S_EQ(op, "-")){
        asm_push("neg %s", a);
    } else if(S_EQ(op, "~")){
        asm_push("not %s", a);
    } else {
        asm_push("cmp rax, 0");
        asm_push("sete al");
        asm_push("movzx eax, al");
    }
}

static void x86_64_branch(int label, int when){
    if(when == EXP64_BRANCH_ALWAYS){
        asm_push("jmp .exp_%i", label);
        return;
    }
    asm_push("cmp rax, 0");
    asm_push("%s .exp_%i", when == EXP64_BRANCH_IF_ZERO ? "je" : "jne", label);
}

static void x86_64_branch_false(const char* op, bool is_signed, const char* label){
    const char* j = "je";
    if(!op){
        asm_push("cmp rax, 0");
    } else {
        asm_push("cmp rax, rcx");
        if(S_EQ(op, "=="))      j = "jne";
        else if(S_EQ(op, "!=")) j = "je";
        else if(S_EQ(op, "<"))  j = is_signed ? "jge" : "jae";
        else if(S_EQ(op, ">"))  j = is_signed ? "jle" : "jbe";
        else if(S_EQ(op, "<=")) j = is_signed ? "jg"  : "ja";
        else                    j = is_signed ? "jl"  : "jb";
    }
    asm_push("%s %s", j, label);
}

static void x86_64_label(int label){
    asm_push(".exp_%i:", label);
}

