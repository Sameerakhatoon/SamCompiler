// B1: drop the top `slots` expression-stack slots: what a nested call
// left behind under a scalar value.
static void x86_64_drop(int slots){
    codegen_stack_add_with_name(8 * slots, "result_value");
}

// Bytes pushed below rbp right now, from the ledger. The saved rbp
// itself sits at [rbp] and does not count.
static size_t codegen_bytes_below_rbp(void){
    return (vector_count(current_function->func.frame.elements) - 1) * DATA_SIZE_DDWORD;
}

// The arguments of a simple call (exp64_call_is_simple): the register
// words are popped into rdi, rsi, rdx, rcx, r8, r9 (from rsi when rdi
// carries the struct result pointer); the rest stay where they are as
// the stack arguments, the first at [rsp], moved down one slot when
// rsp needs the 16-byte alignment SysV wants at the call. Returns the
// bytes left above rsp.
static int x86_64_call_simple(const struct exp64_call* call){
    int stack_args = call->slots - call->reg_words;
    for(int i = 0; i < call->reg_words; i++){
        asm_push_ins_pop(codegen_arg_registers[call->first_reg + i], STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    bool pad = (codegen_bytes_below_rbp() % C_STACK_ALIGNMENT) != 0;
    if(pad){
        asm_push("sub rsp, 8");
        for(int i = 0; i < stack_args; i++){
            asm_push("mov r11, [rsp+%i]", 8 + 8 * i);
            asm_push("mov [rsp+%i], r11", 8 * i);
        }
    }
    for(int i = 0; i < stack_args; i++){
        stackframe_pop_expecting(current_function, STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    return 8 * stack_args + (pad ? 8 : 0);
}

// B1: the arguments of any other call. An outgoing area goes below
// the expression stack (rsp 16-byte aligned again): the stack words
// are copied to it in order, then the register words are loaded from
// their slots. Returns the bytes above rsp: the area and the slots.
static int x86_64_call_general(const struct exp64_call* call){
    int area = align_value(call->area, 8);
    if((codegen_bytes_below_rbp() + area) % C_STACK_ALIGNMENT){
        area += 8;
    }
    if(area){
        asm_push("sub rsp, %i", area);
    }
    for(int pass = 0; pass < 2; pass++){
        for(int i = 0; i < call->count; i++){
            const struct exp64_arg* a = &call->args[i];
            int from = area + 8 * a->slot;
            if(a->kind == EXP64_ARG_REF){
                if(pass == 0){
                    for(int w = 0; w < a->words; w++){
                        asm_push("mov r11, [rsp+%i]", from + 8 * w);
                        asm_push("mov [rsp+%i], r11", a->copy + 8 * w);
                    }
                    if(a->stack >= 0){
                        asm_push("lea r11, [rsp+%i]", a->copy);
                        asm_push("mov [rsp+%i], r11", 8 * a->stack);
                    }
                } else if(a->reg >= 0){
                    asm_push("lea %s, [rsp+%i]", codegen_arg_registers[a->reg], a->copy);
                }
                continue;
            }
            if(a->fp){
                if(pass == 1){
                    asm_push("movq xmm%i, [rsp+%i]", a->reg, from);
                }
                continue;
            }
            if(a->pieces){
                // a struct with floating members, by its
                // eightbytes: SSE ones to xmm, INTEGER ones to the
                // general registers.
                for(int k = 0; k < a->pieces && pass == 1; k++){
                    const struct exp64_piece* p = &a->piece[k];
                    if(!p->fp){
                        asm_push("mov %s, [rsp+%i]", codegen_arg_registers[p->reg], from + p->offset);
                    } else if(p->size == DATA_SIZE_DWORD){
                        asm_push("movd xmm%i, dword [rsp+%i]", p->reg, from + p->offset);
                    } else {
                        asm_push("movq xmm%i, [rsp+%i]", p->reg, from + p->offset);
                    }
                }
                continue;
            }
            for(int w = 0; w < a->words; w++){
                if(w >= a->reg_words && pass == 0){
                    asm_push("mov r11, [rsp+%i]", from + 8 * w);
                    asm_push("mov [rsp+%i], r11", 8 * (a->stack + w - a->reg_words));
                } else if(w < a->reg_words && pass == 1){
                    asm_push("mov %s, [rsp+%i]", codegen_arg_registers[a->reg + w], from + 8 * w);
                }
            }
        }
    }
    for(int i = 0; i < call->slots; i++){
        stackframe_pop(current_function);
    }
    return area + 8 * call->slots;
}

// A call. The arguments are on the expression stack over the callee's
// address (when it is not a named function) and the room for a
// returned struct. A struct of up to 16 bytes comes back in rax:rdx
// and is stored into the room; a bigger one is written there through
// the pointer in rdi.
static void x86_64_call(const struct exp64_call* call){
    int above = call->simple ? x86_64_call_simple(call) : x86_64_call_general(call);
    if(call->symbol){
        codegen_symbol_into("r11", call->symbol);
    } else {
        asm_push("mov r11, [rsp+%i]", above);
    }
    if(call->struct_size && !call->struct_in_regs){
        asm_push("lea rdi, [rsp+%i]", above + (call->symbol ? 0 : 8));
    }
    // al = number of vector registers used, for variadic callees
    // such as printf.
    if(call->fp_regs){
        asm_push("mov eax, %i", call->fp_regs);
    } else {
        asm_push("xor eax, eax");
    }
    asm_push("call r11");
    if(above){
        asm_push("add rsp, %i", above);
    }
    if(!call->symbol){
        asm_push_ins_pop("rcx", STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    if(call->float_return){
        x86_64_from_xmm("rax", 0, call->float_return);
    }
    if(call->struct_size){
        if(call->ld_return){
            // a long double comes back in st0.
            asm_push("fstp tword [rsp]");
        } else if(call->return_pieces){
            // SSE eightbytes from xmm0, xmm1, INTEGER ones
            // from rax, rdx.
            for(int k = 0; k < call->return_pieces; k++){
                const struct exp64_piece* p = &call->return_piece[k];
                if(!p->fp){
                    asm_push("mov [rsp+%i], %s", p->offset, p->reg ? "rdx" : "rax");
                } else if(p->size == DATA_SIZE_DWORD){
                    asm_push("movd dword [rsp+%i], xmm%i", p->offset, p->reg);
                } else {
                    asm_push("movq [rsp+%i], xmm%i", p->offset, p->reg);
                }
            }
        } else if(call->struct_in_regs){
            asm_push("mov [rsp], rax");
            if(call->struct_size > 8){
                asm_push("mov [rsp+8], rdx");
            }
        }
        asm_push("mov rax, rsp");
    }
}

static void x86_64_asm_text(const char* text){
    asm_push("%s", text);
}

// ---------------------------------------------------------------
// Floating point (SSE2). A value travels in rax as its bits and is
// moved to xmm0 (and the right operand from rcx to xmm1) for each
// operation. rdx and r11 are scratch; rcx is kept.
// ---------------------------------------------------------------

static const char* x86_64_fsuffix(int size){
    return size == DATA_SIZE_DWORD ? "ss" : "sd";
}

// xmm<n> = the float or double in the 64-bit register reg, and back.
static void x86_64_to_xmm(int n, const char* reg, int size){
    if(size == DATA_SIZE_DWORD){
        asm_push("movd xmm%i, %s", n, codegen_sub_register(reg, DATA_SIZE_DWORD));
    } else {
        asm_push("movq xmm%i, %s", n, reg);
    }
}

static void x86_64_from_xmm(const char* reg, int n, int size){
    if(size == DATA_SIZE_DWORD){
        asm_push("movd %s, xmm%i", codegen_sub_register(reg, DATA_SIZE_DWORD), n);
    } else {
        asm_push("movq %s, xmm%i", reg, n);
    }
}

static void x86_64_fbinop(const char* op, int size){
    const char* ins = S_EQ(op, "+") ? "add" : S_EQ(op, "-") ? "sub" : S_EQ(op, "*") ? "mul" : "div";
    x86_64_to_xmm(0, "rax", size);
    x86_64_to_xmm(1, "rcx", size);
    asm_push("%s%s xmm0, xmm1", ins, x86_64_fsuffix(size));
    x86_64_from_xmm("rax", 0, size);
}

// ucomis sets ZF, PF and CF; an unordered pair (a NaN) sets all three,
// so a > b is `seta` with b < a swapped round, and == also wants PF
// clear.
static void x86_64_fcompare(const char* op, int size){
    x86_64_to_xmm(0, "rax", size);
    x86_64_to_xmm(1, "rcx", size);
    const char* cmp = size == DATA_SIZE_DWORD ? "ucomiss" : "ucomisd";
    if(S_EQ(op, "==") || S_EQ(op, "!=")){
        bool eq = S_EQ(op, "==");
        asm_push("%s xmm0, xmm1", cmp);
        asm_push(eq ? "sete al" : "setne al");
        asm_push(eq ? "setnp dl" : "setp dl");
        asm_push(eq ? "and al, dl" : "or al, dl");
    } else {
        bool swap = S_EQ(op, "<") || S_EQ(op, "<=");
        asm_push("%s %s", cmp, swap ? "xmm1, xmm0" : "xmm0, xmm1");
        asm_push((S_EQ(op, "<") || S_EQ(op, ">")) ? "seta al" : "setae al");
    }
    asm_push("movzx eax, al");
}

// cvtsi2s converts a signed 64-bit integer. An unsigned one of 2^63 or
// more is halved first (keeping the low bit, so it still rounds right)
// and doubled after.
static void x86_64_int_to_float(int size, bool from_u64){
    const char* s = x86_64_fsuffix(size);
    if(!from_u64){
        asm_push("cvtsi2%s xmm0, rax", s);
        x86_64_from_xmm("rax", 0, size);
        return;
    }
    int big = codegen_label_count();
    int done = codegen_label_count();
    asm_push("test rax, rax");
    asm_push("js .fp_%i", big);
    asm_push("cvtsi2%s xmm0, rax", s);
    asm_push("jmp .fp_%i", done);
    asm_push(".fp_%i:", big);
    asm_push("mov rdx, rax");
    asm_push("shr rdx, 1");
    asm_push("and eax, 1");
    asm_push("or rdx, rax");
    asm_push("cvtsi2%s xmm0, rdx", s);
    asm_push("add%s xmm0, xmm0", s);
    asm_push(".fp_%i:", done);
    x86_64_from_xmm("rax", 0, size);
}

// cvtts2si truncates to a signed 64-bit integer. For an unsigned one,
// a value of 2^63 or more has 2^63 taken off first and its top bit
// set again after.
static void x86_64_float_to_int(int size, bool to_u64){
    const char* s = x86_64_fsuffix(size);
    x86_64_to_xmm(0, "rax", size);
    if(!to_u64){
        asm_push("cvtt%s2si rax, xmm0", s);
        return;
    }
    int big = codegen_label_count();
    int done = codegen_label_count();
    asm_push("mov rdx, %s", size == DATA_SIZE_DWORD ? "0x5f000000" : "0x43e0000000000000");
    x86_64_to_xmm(1, "rdx", size);
    asm_push("ucomi%s xmm0, xmm1", s);
    asm_push("jae .fp_%i", big);
    asm_push("cvtt%s2si rax, xmm0", s);
    asm_push("jmp .fp_%i", done);
    asm_push(".fp_%i:", big);
    asm_push("sub%s xmm0, xmm1", s);
    asm_push("cvtt%s2si rax, xmm0", s);
    asm_push("btc rax, 63");
    asm_push(".fp_%i:", done);
}

static void x86_64_float_resize(int from, int to){
    x86_64_to_xmm(0, "rax", from);
    asm_push("cvt%s2%s xmm0, xmm0", x86_64_fsuffix(from), x86_64_fsuffix(to));
    x86_64_from_xmm("rax", 0, to);
}

// the stack pointer, for variable-length arrays.
static void x86_64_sp_get(void){
    asm_push("mov rax, rsp");
}

static void x86_64_sp_set(void){
    asm_push("mov rsp, rax");
}

// ---------------------------------------------------------------
// long double, the x87 80-bit format in 16 bytes. A value is
// its address in rax (rcx for the right operand); the x87 stack is
// empty between operations.
// ---------------------------------------------------------------

static void x86_64_slot_address(int slots){
    asm_push("lea rax, [rsp+%i]", DATA_SIZE_DDWORD * slots);
}

// st0 = [rax], st1 = [rcx], or the other way round with swap.
static void x86_64_ld_load_pair(bool swap){
    asm_push("fld tword [%s]", swap ? "rax" : "rcx");
    asm_push("fld tword [%s]", swap ? "rcx" : "rax");
}

// [rsp] = [rax] op [rcx]: st1 = left, st0 = right, and the popping
// form leaves st1 op st0.
static void x86_64_ld_arith(const char* op){
    const char* ins = S_EQ(op, "+") ? "faddp" : S_EQ(op, "-") ? "fsubp" : S_EQ(op, "*") ? "fmulp" : "fdivp";
    x86_64_ld_load_pair(true);
    asm_push("%s st1, st0", ins);
    asm_push("fstp tword [rsp]");
    asm_push("mov rax, rsp");
}

// fucomip sets ZF, PF and CF as ucomisd does: a < b is b > a with the
// operands swapped round.
static void x86_64_ld_compare(const char* op){
    bool swap = S_EQ(op, "<") || S_EQ(op, "<=");
    x86_64_ld_load_pair(swap);
    asm_push("fucomip st0, st1");
    asm_push("fstp st0");
    if(S_EQ(op, "==") || S_EQ(op, "!=")){
        bool eq = S_EQ(op, "==");
        asm_push(eq ? "sete al" : "setne al");
        asm_push(eq ? "setnp dl" : "setp dl");
        asm_push(eq ? "and al, dl" : "or al, dl");
    } else {
        asm_push((S_EQ(op, "<") || S_EQ(op, ">")) ? "seta al" : "setae al");
    }
    asm_push("movzx eax, al");
}

static void x86_64_ld_truth(void){
    asm_push("fld tword [rax]");
    asm_push("fldz");
    asm_push("fucomip st0, st1");
    asm_push("fstp st0");
    asm_push("setne al");
    asm_push("setp dl");
    asm_push("or al, dl");
    asm_push("movzx eax, al");
}

// [rsp] = rax as a long double. An unsigned long of 2^63 or more loads
// as a negative one, and 2^64 is added.
static void x86_64_ld_from(int kind){
    asm_push("mov [rsp], rax");
    if(kind == EXP64_LD_FLOAT){
        asm_push("fld dword [rsp]");
    } else if(kind == EXP64_LD_DOUBLE){
        asm_push("fld qword [rsp]");
    } else {
        asm_push("fild qword [rsp]");
    }
    if(kind == EXP64_LD_U64){
        int done = codegen_label_count();
        asm_push("test rax, rax");
        asm_push("jns .fp_%i", done);
        asm_push("mov dword [rsp+8], 0x5f800000");
        asm_push("fadd dword [rsp+8]");
        asm_push(".fp_%i:", done);
    }
    asm_push("fstp tword [rsp]");
    asm_push("mov rax, rsp");
}

// rax = st0 truncated toward zero, popped: the control word set to
// chop for the fistp, then restored. [rsp] to [rsp+16] are scratch.
static void x86_64_ld_truncate(void){
    asm_push("fnstcw [rsp+8]");
    asm_push("mov dx, [rsp+8]");
    asm_push("or dx, 0x0c00");
    asm_push("mov [rsp+10], dx");
    asm_push("fldcw [rsp+10]");
    asm_push("fistp qword [rsp]");
    asm_push("fldcw [rsp+8]");
    asm_push("mov rax, [rsp]");
}

// rax = the long double at rax as a float or double (its bits), or
// truncated to a long or unsigned long; for the unsigned one, a value of
// 2^63 or more has 2^63 taken off first and its top bit set again after.
static void x86_64_ld_to(int kind){
    asm_push("fld tword [rax]");
    asm_push("sub rsp, 16");
    if(kind == EXP64_LD_FLOAT){
        asm_push("fstp dword [rsp]");
        asm_push("mov eax, [rsp]");
    } else if(kind == EXP64_LD_DOUBLE){
        asm_push("fstp qword [rsp]");
        asm_push("mov rax, [rsp]");
    } else if(kind == EXP64_LD_S64){
        x86_64_ld_truncate();
    } else {
        int small = codegen_label_count();
        int done = codegen_label_count();
        asm_push("mov dword [rsp], 0x5f000000");
        asm_push("fld dword [rsp]");
        asm_push("fucomip st0, st1");
        asm_push("ja .fp_%i", small);
        asm_push("fld dword [rsp]");
        asm_push("fsubp st1, st0");
        x86_64_ld_truncate();
        asm_push("btc rax, 63");
        asm_push("jmp .fp_%i", done);
        asm_push(".fp_%i:", small);
        x86_64_ld_truncate();
        asm_push(".fp_%i:", done);
    }
    asm_push("add rsp, 16");
}

