static int riscv64_skip_count;

static void riscv64_from_freg(const char* freg, int size);
static void riscv64_to_freg(const char* freg, const char* reg, int size);

static const char* riscv64_reg(int reg){
    return reg ? "a1" : "a0";
}

static void riscv64_push(struct datatype* dtype){
    asm_push_reg("a0", STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value", dtype);
}

static void riscv64_pop(int reg){
    asm_push_ins_pop(riscv64_reg(reg), STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
}

static void riscv64_mov_r1(void){
    asm_push("mv a1, a0");
}

static void riscv64_swap(void){
    asm_push("mv t3, a0");
    asm_push("mv a0, a1");
    asm_push("mv a1, t3");
}

static void riscv64_imm(int reg, long long value){
    codegen_mov_imm(riscv64_reg(reg), value);
}

static void riscv64_frame_address(int offset){
    codegen_add_imm("a0", "s0", offset);
}

static void riscv64_symbol_address(const char* name){
    codegen_c_symbol_into("a0", name);
}

static void riscv64_string_address(const char* str){
    codegen_symbol_into("a0", codegen_register_string(str));
}

static void riscv64_add_imm(long long value){
    if(value != 0){
        codegen_add_imm("a0", "a0", value);
    }
}

static void riscv64_mul_imm(int reg, long long value){
    if(value != 1){
        codegen_mov_imm("t3", value);
        asm_push("mul %s, %s, t3", riscv64_reg(reg), riscv64_reg(reg));
    }
}

static void riscv64_load(int size, bool is_signed){
    switch(size){
        case DATA_SIZE_BYTE:  asm_push("%s a0, 0(a0)", is_signed ? "lb" : "lbu"); break;
        case DATA_SIZE_WORD:  asm_push("%s a0, 0(a0)", is_signed ? "lh" : "lhu"); break;
        case DATA_SIZE_DWORD: asm_push("%s a0, 0(a0)", is_signed ? "lw" : "lwu"); break;
        default:              asm_push("ld a0, 0(a0)"); break;
    }
}

static const char* riscv64_store_ins(int size){
    return size == 1 ? "sb" : size == 2 ? "sh" : size == 4 ? "sw" : "sd";
}

static const char* riscv64_load_ins(int size, bool is_signed){
    if(size == DATA_SIZE_BYTE){
        return is_signed ? "lb" : "lbu";
    }
    if(size == DATA_SIZE_WORD){
        return is_signed ? "lh" : "lhu";
    }
    if(size == DATA_SIZE_DWORD){
        return is_signed ? "lw" : "lwu";
    }
    return "ld";
}

static void riscv64_store(int size){
    asm_push("%s a0, 0(a1)", riscv64_store_ins(size));
}

static int riscv64_piece(int off, int size){
    int left = size - off;
    return left >= 8 ? 8 : left >= 4 ? 4 : left >= 2 ? 2 : 1;
}

// Copy `size` bytes from [a1] to [a0] through t1. The offsets are
// stepped into the base registers so they never outgrow 12 bits.
static void riscv64_copy(int size){
    asm_push("mv t2, a1");
    asm_push("mv t3, a0");
    for(int off = 0; off < size; ){
        int piece = riscv64_piece(off, size);
        asm_push("%s t1, 0(t2)", piece == 1 ? "lbu" : piece == 2 ? "lhu" : piece == 4 ? "lwu" : "ld");
        asm_push("%s t1, 0(t3)", riscv64_store_ins(piece));
        asm_push("addi t2, t2, %i", piece);
        asm_push("addi t3, t3, %i", piece);
        off += piece;
    }
}

// B1: the `size` (1 to 8) bytes at off(base) into dst, zero extended,
// reading no byte past them: 3, 5, 6 and 7 bytes are put together from
// 4, 2 and 1 byte pieces through t5.
static void riscv64_load_bytes(const char* dst, const char* base, int off, int size){
    for(int done = 0; done < size; ){
        int piece = riscv64_piece(done, size);
        const char* r = done ? "t5" : dst;
        asm_push("%s %s, %i(%s)", piece == 1 ? "lbu" : piece == 2 ? "lhu" : piece == 4 ? "lwu" : "ld", r, off + done, base);
        if(done){
            asm_push("slli t5, t5, %i", 8 * done);
            asm_push("or %s, %s, t5", dst, dst);
        }
        done += piece;
    }
}

static void riscv64_push_struct(int size){
    struct datatype word = { .type = DATA_TYPE_LONG, .type_str = "long", .size = DATA_SIZE_DDWORD };
    asm_push("mv t4, a0");
    for(int w = align_value(size, DATA_SIZE_DDWORD) / DATA_SIZE_DDWORD - 1; w >= 0; w--){
        int bytes = size - DATA_SIZE_DDWORD * w;
        const char* base = "t4";
        int off = DATA_SIZE_DDWORD * w;
        if(off + DATA_SIZE_DDWORD > 2048){
            codegen_add_imm("t6", "t4", off);
            base = "t6";
            off = 0;
        }
        riscv64_load_bytes("a0", base, off, bytes > DATA_SIZE_DDWORD ? DATA_SIZE_DDWORD : bytes);
        riscv64_push(&word);
    }
}

static void riscv64_zero_frame(int offset, int size){
    codegen_add_imm("t2", "s0", offset);
    for(int off = 0; off < size; ){
        int piece = riscv64_piece(off, size);
        asm_push("%s zero, 0(t2)", riscv64_store_ins(piece));
        asm_push("addi t2, t2, %i", piece);
        off += piece;
    }
}

// Widen the low `size` bytes of a register back to a canonical 64-bit
// value.
static void riscv64_extend(int reg, int size, bool is_signed){
    const char* r = riscv64_reg(reg);
    switch(size){
        case DATA_SIZE_BYTE:
            if(is_signed){ asm_push("slli %s, %s, 56", r, r); asm_push("srai %s, %s, 56", r, r); }
            else         { asm_push("andi %s, %s, 255", r, r); }
            break;
        case DATA_SIZE_WORD:
            asm_push("slli %s, %s, 48", r, r);
            asm_push("%s %s, %s, 48", is_signed ? "srai" : "srli", r, r);
            break;
        case DATA_SIZE_DWORD:
            if(is_signed){ asm_push("sext.w %s, %s", r, r); }
            else         { asm_push("slli %s, %s, 32", r, r); asm_push("srli %s, %s, 32", r, r); }
            break;
    }
}

// a0 = a0 <op> a1 on 32 or 64 bits: the *w forms compute on 32 bits.
// exp64 re-extends a 32-bit result.
static void riscv64_binop(const char* op, int size, bool is_signed){
    const char* w = size == DATA_SIZE_DDWORD ? "" : "w";
    const char* ins = 0;
    if(S_EQ(op, "+"))       ins = "add";
    else if(S_EQ(op, "-"))  ins = "sub";
    else if(S_EQ(op, "*"))  ins = "mul";
    else if(S_EQ(op, "<<")) ins = "sll";
    else if(S_EQ(op, ">>")) ins = is_signed ? "sra" : "srl";
    else if(S_EQ(op, "/"))  ins = is_signed ? "div" : "divu";
    else if(S_EQ(op, "%"))  ins = is_signed ? "rem" : "remu";
    if(ins){
        asm_push("%s%s a0, a0, a1", ins, w);
        return;
    }
    // The bitwise operations have no 32-bit forms and need none.
    if(S_EQ(op, "&"))       asm_push("and a0, a0, a1");
    else if(S_EQ(op, "|"))  asm_push("or a0, a0, a1");
    else if(S_EQ(op, "^"))  asm_push("xor a0, a0, a1");
    else compiler_error(current_process, "riscv64: no instruction for %s\n", op);
}

// Both values are canonical, so one 64-bit compare serves every type.
static void riscv64_compare(const char* op, bool is_signed){
    const char* slt = is_signed ? "slt" : "sltu";
    if(S_EQ(op, "==")){
        asm_push("sub a0, a0, a1");
        asm_push("seqz a0, a0");
    } else if(S_EQ(op, "!=")){
        asm_push("sub a0, a0, a1");
        asm_push("snez a0, a0");
    } else if(S_EQ(op, "<")){
        asm_push("%s a0, a0, a1", slt);
    } else if(S_EQ(op, ">")){
        asm_push("%s a0, a1, a0", slt);
    } else if(S_EQ(op, "<=")){
        asm_push("%s a0, a1, a0", slt);
        asm_push("xori a0, a0, 1");
    } else {
        asm_push("%s a0, a0, a1", slt);
        asm_push("xori a0, a0, 1");
    }
}

static void riscv64_unop(const char* op, int size){
    if(S_EQ(op, "-")){
        asm_push(size == DATA_SIZE_DDWORD ? "neg a0, a0" : "negw a0, a0");
    } else if(S_EQ(op, "~")){
        asm_push("not a0, a0");
    } else {
        asm_push("seqz a0, a0");
    }
}

static void riscv64_branch(int label, int when){
    if(when == EXP64_BRANCH_ALWAYS){
        asm_push("j .Lexp_%i", label);
        return;
    }
    asm_push("%s a0, .Lexp_%i", when == EXP64_BRANCH_IF_ZERO ? "beqz" : "bnez", label);
}

// Branch offsets are 12 bits; the test jumps over a `j`, which
// reaches any label of the function.
static void riscv64_branch_false(const char* op, bool is_signed, const char* label){
    const char* u = is_signed ? "" : "u";
    int skip = ++riscv64_skip_count;
    if(!op)                 asm_push("bnez a0, .Ltrue_%i", skip);
    else if(S_EQ(op, "==")) asm_push("beq a0, a1, .Ltrue_%i", skip);
    else if(S_EQ(op, "!=")) asm_push("bne a0, a1, .Ltrue_%i", skip);
    else if(S_EQ(op, "<"))  asm_push("blt%s a0, a1, .Ltrue_%i", u, skip);
    else if(S_EQ(op, ">"))  asm_push("blt%s a1, a0, .Ltrue_%i", u, skip);
    else if(S_EQ(op, "<=")) asm_push("bge%s a1, a0, .Ltrue_%i", u, skip);
    else                    asm_push("bge%s a0, a1, .Ltrue_%i", u, skip);
    asm_push("j %s", label);
    asm_push(".Ltrue_%i:", skip);
}

static void riscv64_label(int label){
    asm_push(".Lexp_%i:", label);
}

static void riscv64_reserve(int size){
    codegen_stack_sub_with_name(align_value(size, CODEGEN_SLOT), "result_value");
}

// B1: drop the top `slots` expression-stack slots: what a nested call
// left behind under a scalar value.
static void riscv64_drop(int slots){
    codegen_stack_add_with_name(CODEGEN_SLOT * slots, "result_value");
}

// B1: `ins reg, off(sp)` for an 8-byte ld or sd, through t6 when off
// is past the 12-bit offset.
static void codegen_sp_word(const char* ins, const char* reg, int off){
    if(off <= 2047){
        asm_push("%s %s, %i(sp)", ins, reg, off);
        return;
    }
    codegen_add_imm("t6", "sp", off);
    asm_push("%s %s, 0(t6)", ins, reg);
}

// The arguments of a simple call (exp64_call_is_simple): the register
// words are popped into a0-a7 (a1-a7 when a0 carries the struct result
// pointer); the rest stay where they are as the stack arguments,
// packed from 16-byte slots down to the 8-byte ones the psABI wants
// (sp stays 16-byte aligned: the area keeps its size). A struct split
// between a7 and the stack is simple too. Returns the bytes left above
// sp.
static int riscv64_call_simple(const struct exp64_call* call){
    int stack_args = call->slots - call->reg_words;
    for(int i = 0; i < call->reg_words; i++){
        asm_push_ins_pop(codegen_arg_registers[call->first_reg + i], STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    for(int i = 1; i < stack_args; i++){
        asm_push("ld t1, %i(sp)", CODEGEN_SLOT * i);
        asm_push("sd t1, %i(sp)", 8 * i);
    }
    for(int i = 0; i < stack_args; i++){
        stackframe_pop_expecting(current_function, STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    return CODEGEN_SLOT * stack_args;
}

// B1: the arguments of any other call. An outgoing area goes below
// the expression stack: the stack words are copied to it in order,
// a struct passed by reference gets its copy there too, then the
// register words are loaded from their slots. Returns the bytes above
// sp: the area and the slots.
static int riscv64_call_general(const struct exp64_call* call){
    int area = align_value(call->area, CODEGEN_SLOT);
    codegen_stack_sp_change(-area);
    for(int pass = 0; pass < 2; pass++){
        for(int i = 0; i < call->count; i++){
            const struct exp64_arg* a = &call->args[i];
            int from = area + CODEGEN_SLOT * a->slot;
            if(a->kind == EXP64_ARG_REF){
                if(pass == 0){
                    for(int w = 0; w < a->words; w++){
                        codegen_sp_word("ld", "t1", from + CODEGEN_SLOT * w);
                        codegen_sp_word("sd", "t1", a->copy + 8 * w);
                    }
                    if(a->stack >= 0){
                        codegen_add_imm("t1", "sp", a->copy);
                        codegen_sp_word("sd", "t1", 8 * a->stack);
                    }
                } else if(a->reg >= 0){
                    codegen_add_imm(codegen_arg_registers[a->reg], "sp", a->copy);
                }
                continue;
            }
            if(a->fp){
                if(pass == 1){
                    char reg[8];
                    snprintf(reg, sizeof(reg), "fa%i", a->reg);
                    codegen_sp_word(a->size == DATA_SIZE_DWORD ? "flw" : "fld", reg, from);
                }
                continue;
            }
            if(a->pieces){
                // a struct of one or two floating members, or
                // one and one integer member: each member to its fa or a
                // register as a scalar of its type. Its words are in
                // 16-byte slots.
                for(int k = 0; k < a->pieces && pass == 1; k++){
                    const struct exp64_piece* p = &a->piece[k];
                    int at = from + CODEGEN_SLOT * (p->offset / 8) + p->offset % 8;
                    char reg[8];
                    snprintf(reg, sizeof(reg), "%s%i", p->fp ? "fa" : "a", p->reg);
                    codegen_sp_word(p->fp ? (p->size == DATA_SIZE_DWORD ? "flw" : "fld")
                                          : riscv64_load_ins(p->size, p->is_signed), reg, at);
                }
                continue;
            }
            for(int w = 0; w < a->words; w++){
                if(w >= a->reg_words && pass == 0){
                    codegen_sp_word("ld", "t1", from + CODEGEN_SLOT * w);
                    codegen_sp_word("sd", "t1", 8 * (a->stack + w - a->reg_words));
                } else if(w < a->reg_words && pass == 1){
                    codegen_sp_word("ld", codegen_arg_registers[a->reg + w], from + CODEGEN_SLOT * w);
                }
            }
        }
    }
    for(int i = 0; i < call->slots; i++){
        stackframe_pop(current_function);
    }
    return area + CODEGEN_SLOT * call->slots;
}

// A call. The arguments are on the expression stack over the callee's
// address (when it is not a named function) and the room for a
// returned struct. A struct of up to 16 bytes comes back in a0:a1 and
// is stored into the room; a bigger one is written there through the
// pointer in a0.
static void riscv64_call(const struct exp64_call* call){
    int above = call->simple ? riscv64_call_simple(call) : riscv64_call_general(call);
    if(call->symbol){
        codegen_c_symbol_into("t0", call->symbol);
    } else {
        codegen_sp_word("ld", "t0", above);
    }
    if(call->struct_size && !call->struct_in_regs){
        codegen_add_imm("a0", "sp", above + (call->symbol ? 0 : CODEGEN_SLOT));
    }
    asm_push("jalr t0");
    codegen_stack_sp_change(above);
    if(!call->symbol){
        asm_push_ins_pop("t0", STACK_FRAME_ELEMENT_TYPE_PUSHED_VALUE, "result_value");
    }
    if(call->float_return){
        riscv64_from_freg("fa0", call->float_return);
    }
    if(call->struct_size){
        if(call->return_pieces){
            // floating members from fa0, fa1, an integer one
            // from a0.
            for(int k = 0; k < call->return_pieces; k++){
                const struct exp64_piece* p = &call->return_piece[k];
                if(p->fp){
                    asm_push("%s fa%i, %i(sp)", p->size == DATA_SIZE_DWORD ? "fsw" : "fsd", p->reg, p->offset);
                } else {
                    asm_push("%s a%i, %i(sp)", riscv64_store_ins(p->size), p->reg, p->offset);
                }
            }
        } else if(call->struct_in_regs){
            asm_push("sd a0, 0(sp)");
            if(call->struct_size > 8){
                asm_push("sd a1, 8(sp)");
            }
        }
        asm_push("mv a0, sp");
    }
}

static void riscv64_asm_text(const char* text){
    asm_push("%s", text);
}

// ---------------------------------------------------------------
// Floating point (the D and F extensions). A value travels in a0 as
// its bits and is moved to ft0 (the right operand from a1 to ft1) for
// each operation; a1 is kept.
// ---------------------------------------------------------------

static const char* riscv64_fsuffix(int size){
    return size == DATA_SIZE_DWORD ? "s" : "d";
}

// fmv.w.x NaN-boxes a float into the 64-bit register, as the F
// instructions on a D machine want.
static void riscv64_to_freg(const char* freg, const char* reg, int size){
    asm_push("fmv.%s.x %s, %s", size == DATA_SIZE_DWORD ? "w" : "d", freg, reg);
}

static void riscv64_from_freg(const char* freg, int size){
    asm_push("fmv.x.%s a0, %s", size == DATA_SIZE_DWORD ? "w" : "d", freg);
}

static void riscv64_fbinop(const char* op, int size){
    const char* ins = S_EQ(op, "+") ? "fadd" : S_EQ(op, "-") ? "fsub" : S_EQ(op, "*") ? "fmul" : "fdiv";
    riscv64_to_freg("ft0", "a0", size);
    riscv64_to_freg("ft1", "a1", size);
    asm_push("%s.%s ft0, ft0, ft1", ins, riscv64_fsuffix(size));
    riscv64_from_freg("ft0", size);
}

// feq, flt and fle give 0 for an unordered pair (a NaN); != is the
// negated feq, so it is 1 then.
static void riscv64_fcompare(const char* op, int size){
    const char* s = riscv64_fsuffix(size);
    riscv64_to_freg("ft0", "a0", size);
    riscv64_to_freg("ft1", "a1", size);
    if(S_EQ(op, "==") || S_EQ(op, "!=")){
        asm_push("feq.%s a0, ft0, ft1", s);
        if(S_EQ(op, "!=")){
            asm_push("xori a0, a0, 1");
        }
    } else if(S_EQ(op, "<")){
        asm_push("flt.%s a0, ft0, ft1", s);
    } else if(S_EQ(op, ">")){
        asm_push("flt.%s a0, ft1, ft0", s);
    } else if(S_EQ(op, "<=")){
        asm_push("fle.%s a0, ft0, ft1", s);
    } else {
        asm_push("fle.%s a0, ft1, ft0", s);
    }
}

static void riscv64_int_to_float(int size, bool from_u64){
    asm_push("fcvt.%s.%s ft0, a0", riscv64_fsuffix(size), from_u64 ? "lu" : "l");
    riscv64_from_freg("ft0", size);
}

// C truncates: the rounding mode is rtz, not the dynamic one.
static void riscv64_float_to_int(int size, bool to_u64){
    riscv64_to_freg("ft0", "a0", size);
    asm_push("fcvt.%s.%s a0, ft0, rtz", to_u64 ? "lu" : "l", riscv64_fsuffix(size));
}

static void riscv64_float_resize(int from, int to){
    riscv64_to_freg("ft0", "a0", from);
    asm_push("fcvt.%s.%s ft0, ft0", riscv64_fsuffix(to), riscv64_fsuffix(from));
    riscv64_from_freg("ft0", to);
}

// the stack pointer, for variable-length arrays.
static void riscv64_sp_get(void){
    asm_push("mv a0, sp");
}

static void riscv64_sp_set(void){
    asm_push("mv sp, a0");
}

// ---------------------------------------------------------------
// long double, IEEE binary128, through the libgcc soft-float
// routines, which take and give it in a pair of integer registers. A
// value is its address in a0 (a1 for the right operand).
// ---------------------------------------------------------------

static void riscv64_slot_address(int slots){
    codegen_add_imm("a0", "sp", CODEGEN_SLOT * slots);
}

// a0:a1 = [a0], a2:a3 = [a1].
static void riscv64_ld_load_pair(void){
    asm_push("ld a2, 0(a1)");
    asm_push("ld a3, 8(a1)");
    asm_push("ld a1, 8(a0)");
    asm_push("ld a0, 0(a0)");
}

static void riscv64_ld_store_result(void){
    asm_push("sd a0, 0(sp)");
    asm_push("sd a1, 8(sp)");
    asm_push("mv a0, sp");
}

static void riscv64_ld_arith(const char* op){
    const char* routine = S_EQ(op, "+") ? "__addtf3" : S_EQ(op, "-") ? "__subtf3" : S_EQ(op, "*") ? "__multf3" : "__divtf3";
    riscv64_ld_load_pair();
    asm_push("call %s", routine);
    riscv64_ld_store_result();
}

// The comparison routines give an int whose sign says the answer, and
// the one that makes the comparison false for an unordered pair.
static void riscv64_ld_compare(const char* op){
    const char* routine = S_EQ(op, "==") ? "__eqtf2" : S_EQ(op, "!=") ? "__netf2" : S_EQ(op, "<") ? "__lttf2"
                        : S_EQ(op, "<=") ? "__letf2" : S_EQ(op, ">") ? "__gttf2" : "__getf2";
    riscv64_ld_load_pair();
    asm_push("call %s", routine);
    if(S_EQ(op, "==")){
        asm_push("seqz a0, a0");
    } else if(S_EQ(op, "!=")){
        asm_push("snez a0, a0");
    } else if(S_EQ(op, "<")){
        asm_push("slt a0, a0, zero");
    } else if(S_EQ(op, "<=")){
        asm_push("slti a0, a0, 1");
    } else if(S_EQ(op, ">")){
        asm_push("sgt a0, a0, zero");
    } else {
        asm_push("slti a0, a0, 0");
        asm_push("xori a0, a0, 1");
    }
}

static void riscv64_ld_truth(void){
    asm_push("ld a1, 8(a0)");
    asm_push("ld a0, 0(a0)");
    asm_push("li a2, 0");
    asm_push("li a3, 0");
    asm_push("call __netf2");
    asm_push("snez a0, a0");
}

static void riscv64_ld_from(int kind){
    if(kind == EXP64_LD_FLOAT){
        asm_push("fmv.w.x fa0, a0");
        asm_push("call __extendsftf2");
    } else if(kind == EXP64_LD_DOUBLE){
        asm_push("fmv.d.x fa0, a0");
        asm_push("call __extenddftf2");
    } else {
        asm_push("call %s", kind == EXP64_LD_S64 ? "__floatditf" : "__floatunditf");
    }
    riscv64_ld_store_result();
}

static void riscv64_ld_to(int kind){
    asm_push("ld a1, 8(a0)");
    asm_push("ld a0, 0(a0)");
    if(kind == EXP64_LD_FLOAT){
        asm_push("call __trunctfsf2");
        asm_push("fmv.x.w a0, fa0");
    } else if(kind == EXP64_LD_DOUBLE){
        asm_push("call __trunctfdf2");
        asm_push("fmv.x.d a0, fa0");
    } else {
        asm_push("call %s", kind == EXP64_LD_S64 ? "__fixtfdi" : "__fixunstfdi");
    }
}

// atomics with the A extension, in the mapping of the RISC-V
// psABI for sequentially consistent accesses: a load between
// `fence rw,rw` and `fence r,rw`, a store after `fence rw,w`, and the
// read-modify-writes as amo*.aqrl or lr/sc.aqrl loops. A byte or
// halfword has no lr/sc of its own: the loop runs on the aligned word
// around it and changes only its bits. A slot is 16 bytes.
static void riscv64_peek(int reg, int depth){
    asm_push("ld %s, %i(sp)", riscv64_reg(reg), CODEGEN_SLOT * depth);
}

static void riscv64_atomic_load(int size, bool is_signed){
    asm_push("fence rw,rw");
    riscv64_load(size, is_signed);
    asm_push("fence r,rw");
}

static void riscv64_atomic_store(int size){
    asm_push("fence rw,w");
    riscv64_store(size);
}

// For a byte or halfword at the address in `address`: t4 = the aligned
// word's address, t6 = the shift of the field in it, a2 = its mask
// there, a4 = ~a2; reg1 and reg2 (when given) are moved into the field
// as out1 and out2.
static void riscv64_atomic_field(const char* address, int size, const char* reg1, const char* out1, const char* reg2, const char* out2){
    asm_push("andi t6, %s, 3", address);
    asm_push("slli t6, t6, 3");
    asm_push("andi t4, %s, -4", address);
    asm_push("li a2, %i", size == DATA_SIZE_BYTE ? 0xff : 0xffff);
    asm_push("and %s, %s, a2", out1, reg1);
    asm_push("sll %s, %s, t6", out1, out1);
    if(reg2){
        asm_push("and %s, %s, a2", out2, reg2);
        asm_push("sll %s, %s, t6", out2, out2);
    }
    asm_push("sll a2, a2, t6");
    asm_push("not a4, a2");
}

static const char* riscv64_atomic_ins(const char* op){
    return S_EQ(op, "+") ? "add" : S_EQ(op, "-") ? "sub" : S_EQ(op, "&") ? "and" : S_EQ(op, "|") ? "or" : "xor";
}

static void riscv64_atomic_rmw(const char* op, int size){
    if(size < DATA_SIZE_DWORD){
        riscv64_atomic_field("a1", size, "a0", "a3", 0, 0);
        asm_push("1: lr.w.aqrl t5, (t4)");
        if(S_EQ(op, "=")){
            asm_push("mv a5, a3");
        } else if(S_EQ(op, "nand")){
            asm_push("and a5, t5, a3");
            asm_push("not a5, a5");
        } else {
            asm_push("%s a5, t5, a3", riscv64_atomic_ins(op));
        }
        asm_push("and a5, a5, a2");
        asm_push("and a6, t5, a4");
        asm_push("or a5, a5, a6");
        asm_push("sc.w.aqrl a6, a5, (t4)");
        asm_push("bnez a6, 1b");
        asm_push("srl a0, t5, t6");
        return;
    }
    const char* w = size == DATA_SIZE_DDWORD ? "d" : "w";
    if(S_EQ(op, "nand")){
        asm_push("1: lr.%s.aqrl t5, (a1)", w);
        asm_push("and t6, t5, a0");
        asm_push("not t6, t6");
        asm_push("sc.%s.aqrl t4, t6, (a1)", w);
        asm_push("bnez t4, 1b");
        asm_push("mv a0, t5");
        return;
    }
    if(S_EQ(op, "-")){
        asm_push("neg a0, a0");
    }
    const char* amo = S_EQ(op, "=") ? "swap" : S_EQ(op, "+") || S_EQ(op, "-") ? "add" : riscv64_atomic_ins(op);
    asm_push("amo%s.%s.aqrl a0, a0, (a1)", amo, w);
}

// The expected value in a1 may be sign extended (a word is compared as
// lr.w loads it, sign extended); a1 is kept.
static void riscv64_atomic_cas(int size, int depth){
    asm_push("ld t4, %i(sp)", CODEGEN_SLOT * depth);
    if(size < DATA_SIZE_DWORD){
        asm_push("mv t5, t4");
        riscv64_atomic_field("t5", size, "a1", "a3", "a0", "a5");
        asm_push("1: lr.w.aqrl t5, (t4)");
        asm_push("and a6, t5, a2");
        asm_push("bne a6, a3, 2f");
        asm_push("and a6, t5, a4");
        asm_push("or a6, a6, a5");
        asm_push("sc.w.aqrl a7, a6, (t4)");
        asm_push("bnez a7, 1b");
        asm_push("2: srl a0, t5, t6");
        return;
    }
    const char* w = size == DATA_SIZE_DDWORD ? "d" : "w";
    asm_push(size == DATA_SIZE_DDWORD ? "mv t6, a1" : "sext.w t6, a1");
    asm_push("1: lr.%s.aqrl t5, (t4)", w);
    asm_push("bne t5, t6, 2f");
    asm_push("sc.%s.aqrl a2, a0, (t4)", w);
    asm_push("bnez a2, 1b");
    asm_push("2: mv a0, t5");
}

static void riscv64_fence(void){
    asm_push("fence rw,rw");
}

// tp is the thread pointer. A variable this file defines is
// local-exec, tp plus its offset; any other initial-exec, its offset
// read from the GOT.
static void riscv64_tls_address(const char* name, bool defined_here){
    if(defined_here){
        asm_push("lui a0, %%tprel_hi(%s)", name);
        asm_push("add a0, a0, tp, %%tprel_add(%s)", name);
        asm_push("addi a0, a0, %%tprel_lo(%s)", name);
        return;
    }
    asm_push("la.tls.ie a0, %s", name);
    asm_push("add a0, a0, tp");
}

