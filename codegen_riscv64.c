// GNU as data directive for a scalar of `size` bytes.
static const char* asm_directive_for_size(size_t size){
    switch(size){
        case DATA_SIZE_BYTE:   return ".byte";
        case DATA_SIZE_WORD:   return ".half";
        case DATA_SIZE_DWORD:  return ".word";
        case DATA_SIZE_DDWORD: return ".dword";
    }
    return 0;
}

// a global's symbol is global unless it is static. In a shared
// object it is also typed and sized: a program that uses it gets a copy
// relocation, which copies that many bytes.
static void codegen_global_label(struct node* node){
    if(node->var.type.flags & DATATYPE_FLAG_IS_STATIC){
        return;
    }
    asm_push(".globl %s", node->var.name);
    if(current_process->flags & COMPILE_PROCESS_PIC){
        asm_push(".type %s, @object", node->var.name);
        asm_push(".size %s, %lu", node->var.name, (unsigned long)variable_size(node));
    }
}

// Align each global to its own size (8 at most), then the label and
// its value. Sizes that are not a scalar become a zero-filled block.
static void codegen_generate_global_data(const char* name, size_t size, const char* value){
    size_t align = size >= 8 ? 8 : size >= 4 ? 4 : size >= 2 ? 2 : 1;
    asm_push(".balign %lu", (unsigned long)align);
    const char* directive = asm_directive_for_size(size);
    if(directive){
        asm_push("%s: %s %s", name, directive, value);
    } else {
        asm_push("%s: .zero %lu", name, (unsigned long)size);
    }
}

static void codegen_generate_global_variable_for_primitive(struct node* node){
    char value[RESOLVER_ADDRESS_MAX];
    if(node->var.val){
        initializer_value_asm(node->var.val, codegen_register_string, value, sizeof(value));
    } else {
        snprintf(value, sizeof(value), "0");
    }
    codegen_generate_global_data(node->var.name, variable_size(node), value);
}

// A global with a brace initializer (or an address): its bytes, leaf by
// leaf, from codegen_emit_initializer.
static const char* codegen_init_gas_size(size_t size){
    switch(size){
        case DATA_SIZE_BYTE:  return ".byte";
        case DATA_SIZE_WORD:  return ".2byte";
        case DATA_SIZE_DWORD: return ".4byte";
        default:              return ".8byte";
    }
}

static void codegen_init_value(size_t size, long long value){
    asm_push("%s %lld", codegen_init_gas_size(size), value);
}

static void codegen_init_symbol(size_t size, const char* symbol){
    asm_push("%s %s", codegen_init_gas_size(size), symbol);
}

static void codegen_init_zero(size_t count){
    asm_push(".zero %lu", (unsigned long)count);
}

static void codegen_generate_global_initializer(struct node* node){
    codegen_global_label(node);
    asm_push(".balign %lu", (unsigned long)datatype_alignment(&node->var.type));
    asm_push("%s:", node->var.name);
    codegen_emit_initializer(node, &(struct initializer_emitter){
        .value        = codegen_init_value,
        .symbol       = codegen_init_symbol,
        .zero         = codegen_init_zero,
        .string_label = codegen_register_string,
    });
}

static void codegen_generate_global_variable_data(struct node* node);

// a thread-local variable's initial image goes to .tdata, or
// to .tbss without an initializer; each thread gets a copy of it. The
// symbols of a TLS section are STT_TLS.
static void codegen_generate_global_variable(struct node* node){
    int flags = node->var.type.flags;
    if(!(flags & DATATYPE_FLAG_IS_THREAD_LOCAL) || (flags & DATATYPE_FLAG_IS_EXTERN)){
        codegen_generate_global_variable_data(node);
        return;
    }
    if(!node->var.val){
        asm_push(".pushsection .tbss,\"awT\",@nobits");
        codegen_global_label(node);
        asm_push(".balign %lu", (unsigned long)datatype_alignment(&node->var.type));
        asm_push("%s: .zero %lu", node->var.name, (unsigned long)variable_size(node));
        asm_push(".popsection");
        codegen_new_scope_entity(node, 0, 0);
        return;
    }
    asm_push(".pushsection .tdata,\"awT\",@progbits");
    codegen_generate_global_variable_data(node);
    asm_push(".popsection");
}

static void codegen_generate_global_variable_data(struct node* node){
    asm_push("# %s %s", node->var.type.type_str, node->var.name);
    if(node->var.val && node->var.val->type == NODE_TYPE_INITIALIZER){
        codegen_generate_global_initializer(node);
        codegen_new_scope_entity(node, 0, 0);
        return;
    }
    if(node->var.type.flags & DATATYPE_FLAG_IS_EXTERN){
        codegen_new_scope_entity(node, 0, 0);
        return;
    }
    codegen_global_label(node);
    if(node->var.type.flags & (DATATYPE_FLAG_IS_ARRAY | DATATYPE_FLAG_IS_POINTER)){
        codegen_generate_global_variable_for_primitive(node);
    } else {
        switch(node->var.type.type){
            case DATA_TYPE_STRUCT:
            case DATA_TYPE_UNION:
                if(node->var.val){
                    compiler_error(current_process, "A struct or union global needs a { } initializer\n");
                }
                codegen_generate_global_data(node->var.name, variable_size(node), "0");
                break;
            default:
                codegen_generate_global_variable_for_primitive(node);
                break;
        }
    }
    codegen_new_scope_entity(node, 0, 0);
}

static void codegen_generate_struct(struct node* node){
    if(node->flags & NODE_FLAG_HAS_VARIABLE_COMBINED){
        codegen_generate_global_variable(node->_struct.var);
    }
}

static void codegen_generate_union(struct node* node){
    if(node->flags & NODE_FLAG_HAS_VARIABLE_COMBINED){
        codegen_generate_global_variable(node->_union.var);
    }
}

static void codegen_generate_global_variable_list(struct node* var_list_node){
    assert(var_list_node->type == NODE_TYPE_VARIABLE_LIST);
    vector_set_peek_pointer(var_list_node->var_list.list, 0);
    struct node* var = vector_peek_ptr(var_list_node->var_list.list);
    while(var){
        codegen_generate_global_variable(var);
        var = vector_peek_ptr(var_list_node->var_list.list);
    }
}

static void codegen_generate_data_section_part(struct node* node){
    switch(node->type){
        case NODE_TYPE_VARIABLE_LIST:
            codegen_generate_global_variable_list(node);
            break;
        case NODE_TYPE_VARIABLE:
            codegen_generate_global_variable(node);
            break;
        case NODE_TYPE_STRUCT:
            codegen_generate_struct(node);
            break;
        case NODE_TYPE_UNION:
            codegen_generate_union(node);
            break;
        default:
            break;
    }
}

static void codegen_generate_data_section(void){
    asm_push(".data");
    struct node* node = codegen_node_next();
    while(node){
        codegen_generate_data_section_part(node);
        node = codegen_node_next();
    }
}

static void codegen_generate_root_node(struct node* node){
    switch(node->type){
        case NODE_TYPE_VARIABLE:
            break;
        case NODE_TYPE_FUNCTION:
            codegen_generate_function(node);
            break;
        default:
            break;
    }
}

static void codegen_generate_root(void){
    asm_push(".text");
    // Instructions are 4 bytes and must be 4-byte aligned.
    asm_push(".p2align 2");
    struct node* node = 0;
    while((node = codegen_node_next()) != 0){
        codegen_generate_root_node(node);
    }
}

// One string as .asciz, with everything outside printable ASCII (and
// the quote and backslash) written as an octal escape.
static void codegen_write_string(struct string_table_element* element){
    // Every input byte takes at most four output bytes. The buffer used
    // to be 4096 bytes and longer strings were cut without a word.
    size_t len = strlen(element->str);
    char* out = malloc(len * 4 + 1);
    size_t n = 0;
    for(const char* c = element->str; *c; c++){
        unsigned char ch = (unsigned char)*c;
        if(ch < 32 || ch >= 127 || ch == '"' || ch == '\\'){
            n += sprintf(out + n, "\\%03o", ch);
        } else {
            out[n++] = ch;
        }
    }
    out[n] = 0;
    asm_push("%s: .asciz \"%s\"", element->label, out);
    free(out);
}

static void codegen_write_strings(void){
    struct code_generator* gen = current_process->generator;
    vector_set_peek_pointer(gen->string_table, 0);
    struct string_table_element* element = vector_peek_ptr(gen->string_table);
    while(element){
        codegen_write_string(element);
        element = vector_peek_ptr(gen->string_table);
    }
}

static const char* codegen_get_label_for_string(const char* str){
    struct code_generator* gen = current_process->generator;
    vector_set_peek_pointer(gen->string_table, 0);
    struct string_table_element* cur = vector_peek_ptr(gen->string_table);
    while(cur){
        if(S_EQ(cur->str, str)){
            return cur->label;
        }
        cur = vector_peek_ptr(gen->string_table);
    }
    return 0;
}

static const char* codegen_register_string(const char* str){
    const char* label = codegen_get_label_for_string(str);
    if(label){
        return label;
    }
    struct string_table_element* el = calloc(1, sizeof(struct string_table_element));
    sprintf((char*)el->label, "str_%i", codegen_label_count());
    el->str = str;
    vector_push(current_process->generator->string_table, &el);
    return el->label;
}

static void codegen_generate_rod(void){
    asm_push(".section .rodata");
    codegen_write_strings();
}

int codegen_riscv64(struct compile_process* process){
    current_process = process;
    exp64_begin(&riscv64_ops, process);
    scope_create_root(process);

    vector_set_peek_pointer(process->node_tree_vec, 0);
    codegen_new_scope(0);
    codegen_generate_data_section();

    vector_set_peek_pointer(process->node_tree_vec, 0);
    codegen_static_locals = vector_create(sizeof(struct node*));
    codegen_generate_root();
    asm_push(".data");
    for(int i = 0; i < vector_count(codegen_static_locals); i++){
        codegen_generate_global_variable(*(struct node**)vector_at(codegen_static_locals, i));
    }
    codegen_finish_scope();

    codegen_generate_rod();
    // The stack is not executable (the linker warns otherwise).
    asm_push(".section .note.GNU-stack,\"\",@progbits");
    return CODEGEN_ALL_OK;
}
